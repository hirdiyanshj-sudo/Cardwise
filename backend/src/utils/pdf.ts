import PDFDocument from 'pdfkit';

function formatInr(amount: number): string {
  return `INR ${Number(amount || 0).toLocaleString('en-IN', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}

export interface StatementPdfInput {
  userName: string;
  userEmail: string;
  card: {
    bank_name: string;
    card_name: string;
    last_four_digits: string;
    card_network: string;
    credit_limit: number;
    available_credit_limit: number;
  };
  statement: {
    statement_month: string;
    billing_period: string;
    statement_generation_date: string;
    payment_due_date: string;
    total_amount_due: number;
    minimum_amount_due: number;
    amount_paid: number;
    payment_status: string;
    reward_points_earned: number;
  };
  transactions: Array<{
    transaction_date: string;
    merchant: string;
    category_name: string;
    transaction_type: string;
    amount: number;
  }>;
}

export function generateStatementPdfBuffer(data: StatementPdfInput): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 45 });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    // Header
    doc.rect(0, 0, doc.page.width, 95).fill('#0B162C');
    doc.fillColor('#FFFFFF').fontSize(22).text('CardWise', 45, 28);
    doc.fillColor('#94A3B8').fontSize(10).text('Smart Credit Card Manager - Statement Summary', 45, 56);
    doc
      .fillColor('#38BDF8')
      .fontSize(11)
      .text(`Statement Month: ${data.statement.statement_month}`, 370, 34, { align: 'right' });
    doc
      .fillColor('#CBD5E1')
      .fontSize(9)
      .text(`Status: ${data.statement.payment_status}`, 370, 52, { align: 'right' });

    doc.moveDown(3.5);
    doc.fillColor('#0F172A').fontSize(12).text(`Cardholder: ${data.userName}`, 45, 115);
    doc.fillColor('#475569').fontSize(10).text(`Email: ${data.userEmail}`, 45, 132);
    doc.text(
      `Card: ${data.card.bank_name} ${data.card.card_name} (•••• ${data.card.last_four_digits}) [${data.card.card_network}]`,
      45,
      148
    );

    // Summary Box
    doc.roundedRect(45, 175, 505, 105, 6).fillAndStroke('#F8FAFC', '#CBD5E1');
    doc.fillColor('#0F172A').fontSize(10);
    doc.text(`Billing Period: ${data.statement.billing_period}`, 60, 190);
    doc.text(`Statement Date: ${data.statement.statement_generation_date}`, 60, 208);
    doc.text(`Payment Due Date: ${data.statement.payment_due_date}`, 60, 226);
    doc.text(`Credit Limit: ${formatInr(data.card.credit_limit)}`, 60, 244);

    doc.text(`Total Amount Due: ${formatInr(data.statement.total_amount_due)}`, 315, 190);
    doc.text(`Minimum Amount Due: ${formatInr(data.statement.minimum_amount_due)}`, 315, 208);
    doc.text(`Amount Paid: ${formatInr(data.statement.amount_paid)}`, 315, 226);
    doc.text(`Reward Points Earned: ${data.statement.reward_points_earned}`, 315, 244);

    // Transactions table
    doc.fillColor('#0F172A').fontSize(13).text('Transactions Included in Period', 45, 300);
    let y = 325;
    doc.rect(45, y, 505, 22).fill('#0F172A');
    doc.fillColor('#FFFFFF').fontSize(9);
    doc.text('Date', 52, y + 7);
    doc.text('Merchant', 135, y + 7);
    doc.text('Category', 310, y + 7);
    doc.text('Type', 415, y + 7);
    doc.text('Amount', 475, y + 7);
    y += 26;

    if (data.transactions.length === 0) {
      doc.fillColor('#64748B').fontSize(10).text('No transactions recorded for this period.', 52, y + 6);
    } else {
      for (const tx of data.transactions.slice(0, 28)) {
        if (y > 740) {
          doc.addPage();
          y = 50;
        }
        doc.fillColor('#1E293B').fontSize(9);
        doc.text(tx.transaction_date.slice(0, 10), 52, y);
        doc.text(tx.merchant.slice(0, 28), 135, y);
        doc.text(tx.category_name.slice(0, 18), 310, y);
        doc.text(tx.transaction_type, 415, y);
        doc.text(formatInr(tx.amount), 460, y, { width: 85, align: 'right' });
        y += 18;
      }
    }

    doc
      .fillColor('#64748B')
      .fontSize(8)
      .text(
        'Generated by CardWise. Never shares full card numbers, CVV, PIN, or OTPs. For personal tracking only.',
        45,
        785,
        { align: 'center', width: 505 }
      );

    doc.end();
  });
}

export interface ExpenseReportPdfInput {
  userName: string;
  periodLabel: string;
  totalSpent: number;
  averageMonthly: number;
  topCategory: string;
  categories: Array<{ category: string; amount: number; percentage: number }>;
  transactions: Array<{
    transaction_date: string;
    card_name: string;
    merchant: string;
    category_name: string;
    amount: number;
  }>;
}

export function generateExpenseReportPdfBuffer(data: ExpenseReportPdfInput): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 45 });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.rect(0, 0, doc.page.width, 85).fill('#0B162C');
    doc.fillColor('#FFFFFF').fontSize(20).text('CardWise Spending & Expense Report', 45, 25);
    doc.fillColor('#94A3B8').fontSize(10).text(`${data.userName} • ${data.periodLabel}`, 45, 52);

    doc.fillColor('#0F172A').fontSize(11).text(`Total Expenditure: ${formatInr(data.totalSpent)}`, 45, 105);
    doc.text(`Average Monthly Spend: ${formatInr(data.averageMonthly)}`, 45, 122);
    doc.text(`Highest Spending Category: ${data.topCategory}`, 45, 139);

    doc.fontSize(13).text('Category Breakdown', 45, 170);
    let y = 192;
    for (const c of data.categories) {
      doc.fillColor('#1E293B').fontSize(10);
      doc.text(`${c.category}`, 50, y);
      doc.text(`${formatInr(c.amount)} (${c.percentage.toFixed(1)}%)`, 320, y, { align: 'right', width: 220 });
      y += 18;
    }

    y += 16;
    doc.fillColor('#0F172A').fontSize(13).text('Recent Expense Transactions', 45, y);
    y += 22;

    doc.rect(45, y, 505, 20).fill('#0F172A');
    doc.fillColor('#FFFFFF').fontSize(9);
    doc.text('Date', 50, y + 6);
    doc.text('Card', 125, y + 6);
    doc.text('Merchant', 240, y + 6);
    doc.text('Category', 370, y + 6);
    doc.text('Amount', 475, y + 6);
    y += 24;

    for (const tx of data.transactions.slice(0, 30)) {
      if (y > 745) {
        doc.addPage();
        y = 50;
      }
      doc.fillColor('#1E293B').fontSize(8.5);
      doc.text(tx.transaction_date.slice(0, 10), 50, y);
      doc.text((tx.card_name || '').slice(0, 18), 125, y);
      doc.text(tx.merchant.slice(0, 22), 240, y);
      doc.text(tx.category_name.slice(0, 16), 370, y);
      doc.text(formatInr(tx.amount), 455, y, { width: 90, align: 'right' });
      y += 16;
    }

    doc.end();
  });
}
